"""Review tables: `wiki/cosmyx/branding-assets/<group>.md`, one per manifest group.

The tables are generated from the manifest (`just brand-table`) and checked by
guard G6, so the wiki always shows what the build applies. The output depends
on the manifest only: no dates, no machine paths.
"""

from __future__ import annotations

from pathlib import Path

from . import GROUPS, MANIFEST_DIR, TABLES_DIR, repo_path, same_text, write_text
from .manifest import STATUSES, Manifest

COLUMNS = ("path", "format", "size", "kind", "source", "status", "usage")


def cell(value) -> str:
    if value is None or value == "":
        return "-"
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(group: str, rows: list) -> str:
    rows = sorted(rows, key=lambda row: row["path"])
    counts = ", ".join(f"{status} {sum(1 for row in rows if row['status'] == status)}" for status in STATUSES)
    lines = [
        f"# Branding assets: {group}",
        "",
        f"Generated by `just brand-table` from `{MANIFEST_DIR}/{group}.json`; do not edit by hand.",
        "See [the branding workflow](../branding.md) for what each status means.",
        "",
        f"Rows: {len(rows)} ({counts}).",
        "",
        "| " + " | ".join(column.capitalize() for column in COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    for row in rows:
        values = [f"`{row['path']}`"] + [cell(row[column]) for column in COLUMNS[1:]]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines) + "\n"


def table_path(root: Path, group: str) -> Path:
    return repo_path(root, f"{TABLES_DIR}/{group}.md")


def write(root: Path, manifest: Manifest) -> list[str]:
    for group in GROUPS:
        write_text(table_path(root, group), table(group, manifest.groups.get(group, [])))
    return [f"{TABLES_DIR}/{group}.md" for group in GROUPS]


def stale(root: Path, manifest: Manifest) -> list[str]:
    """Tables that are missing or differ from what `write` would produce."""
    result = []
    for group in GROUPS:
        path = table_path(root, group)
        if not path.is_file() or not same_text(path, table(group, manifest.groups.get(group, []))):
            result.append(f"{TABLES_DIR}/{group}.md")
    return result
