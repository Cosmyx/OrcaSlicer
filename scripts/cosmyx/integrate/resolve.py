"""Text resolutions of the known integration conflict kinds.

Every function here is pure: it takes the text of a conflicted file (written
with `merge.conflictStyle=diff3`) and returns the resolved text, or raises
`Unresolvable` when a hunk is not of the known kind. The callers treat that as
an unknown conflict and stop.

Known kinds:

- `CHANGELOG.md`: both sides added slot blocks (`<!-- cosmyx-slot: Tn -->`
  plus its lines) at the same place. Union of the blocks: ours first, then
  the blocks only theirs has. For a marker both sides carry, theirs' extra
  entries go above ours (newest first).
- `scripts/cosmyx/tests/test_foundation.py` (`SLOTS_BY_AREA`) and
  `wiki/decisions/0003-changelog-slots.md` (markers by area): both sides
  extended the same slot list lines. Union of the slots, ordered by the order
  of the markers in the resolved `CHANGELOG.md`.
- Branding manifests and review tables: see `validated_paths`; the side is
  taken by the caller, then regenerated by the branding engine.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

MARKER_RE = re.compile(r"^<!-- cosmyx-slot: (T\d+[a-z]?) -->\s*$")
CONFLICT_LINE_RE = re.compile(r"^(<<<<<<<|\|\|\|\|\|\|\||=======|>>>>>>>)( |$)", re.MULTILINE)

CHANGELOG = "CHANGELOG.md"
SLOTS_PY = "scripts/cosmyx/tests/test_foundation.py"
SLOTS_MD = "wiki/decisions/0003-changelog-slots.md"
BRAND_PREFIXES = ("cosmyx-src/branding/manifest/", "wiki/cosmyx/branding-assets/")
BRAND_SUFFIXES = {"cosmyx-src/branding/manifest/": ".json", "wiki/cosmyx/branding-assets/": ".md"}


class Unresolvable(Exception):
    """A conflict hunk that is not of a known kind."""


@dataclass
class Hunk:
    ours: list[str]
    base: list[str] | None
    theirs: list[str]
    start: int  # 1-based line of the `<<<<<<<` marker
    extra: dict = field(default_factory=dict)


def kind_of(path: str) -> str | None:
    """Return the known conflict kind of a repository path, or None."""
    if path == CHANGELOG:
        return "changelog"
    if path in (SLOTS_PY, SLOTS_MD):
        return "slot-list"
    for prefix in BRAND_PREFIXES:
        rest = path[len(prefix):]
        if path.startswith(prefix) and "/" not in rest and rest.endswith(BRAND_SUFFIXES[prefix]):
            return "branding"
    return None


def has_conflict_markers(text: str) -> bool:
    return bool(re.search(r"^<<<<<<< ", text, re.MULTILINE)) and bool(re.search(r"^>>>>>>> ", text, re.MULTILINE))


def split_text(text: str) -> tuple[list[str], str]:
    """Split into lines without line ends; return them and the line end to write back."""
    eol = "\r\n" if "\r\n" in text else "\n"
    return text.replace("\r\n", "\n").split("\n"), eol


def parse(text: str) -> list[object]:
    """Return a list of plain lines (str) and Hunk objects, in file order."""
    lines, _ = split_text(text)
    out: list[object] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.startswith("<<<<<<< ") and line != "<<<<<<<":
            out.append(line)
            index += 1
            continue
        start = index + 1
        ours: list[str] = []
        base: list[str] | None = None
        theirs: list[str] = []
        section = "ours"
        index += 1
        while True:
            if index >= len(lines):
                raise Unresolvable(f"unterminated conflict at line {start}")
            line = lines[index]
            if line.startswith("||||||| ") or line == "|||||||":
                section, base = "base", []
            elif line == "=======":
                section = "theirs"
            elif line.startswith(">>>>>>> ") or line == ">>>>>>>":
                index += 1
                break
            elif section == "ours":
                ours.append(line)
            elif section == "base":
                base.append(line)
            else:
                theirs.append(line)
            index += 1
        out.append(Hunk(ours, base, theirs, start))
    return out


def hunks(text: str) -> list[Hunk]:
    return [item for item in parse(text) if isinstance(item, Hunk)]


def resolve_text(text: str, resolver) -> str:
    """Resolve every hunk of `text` with `resolver(hunk) -> list[str]`."""
    _, eol = split_text(text)
    out: list[str] = []
    for item in parse(text):
        if isinstance(item, Hunk):
            out.extend(resolver(item))
        else:
            out.append(item)
    return eol.join(out)


def summarize(text: str, limit: int = 3) -> list[str]:
    """One line per conflict hunk, for the stop report."""
    try:
        found = hunks(text)
    except Unresolvable as error:
        return [str(error)]
    lines = []
    for hunk in found[:limit]:
        first_ours = next((line for line in hunk.ours if line.strip()), "")
        first_theirs = next((line for line in hunk.theirs if line.strip()), "")
        lines.append(
            f"line {hunk.start}: ours {len(hunk.ours)} lines ({first_ours.strip()[:60]!r}), "
            f"theirs {len(hunk.theirs)} lines ({first_theirs.strip()[:60]!r})"
        )
    if len(found) > limit:
        lines.append(f"... {len(found) - limit} more hunks")
    return lines


def _require_base_kept(hunk: Hunk) -> None:
    """Only pure additions on both sides are unions: no base line may be dropped."""
    for line in hunk.base or []:
        if line.strip() and (line not in hunk.ours or line not in hunk.theirs):
            raise Unresolvable(f"line {hunk.start}: a side removed or changed {line.strip()[:60]!r}")


# CHANGELOG.md


def _blocks(lines: list[str]) -> tuple[list[str], list[tuple[str, str, list[list[str]]]]]:
    """Split into a preamble and (marker id, marker line, entries) blocks."""
    preamble: list[str] = []
    blocks: list[tuple[str, str, list[list[str]]]] = []
    for line in lines:
        match = MARKER_RE.match(line)
        if match:
            blocks.append((match.group(1), line, []))
        elif not blocks:
            preamble.append(line)
        elif line.startswith("- "):
            blocks[-1][2].append([line])
        elif not line.strip():
            continue
        elif blocks[-1][2] and line.startswith(" "):
            blocks[-1][2][-1].append(line)
        else:
            raise Unresolvable(f"unexpected line in a slot block: {line.strip()[:60]!r}")
    return preamble, blocks


def _strip_blank(lines: list[str]) -> list[str]:
    start, end = 0, len(lines)
    while start < end and not lines[start].strip():
        start += 1
    while end > start and not lines[end - 1].strip():
        end -= 1
    return lines[start:end]


def _edge_blanks(lines: list[str]) -> tuple[int, int]:
    lead = 0
    while lead < len(lines) and not lines[lead].strip():
        lead += 1
    if lead == len(lines):
        return lead, 0
    trail = 0
    while not lines[len(lines) - 1 - trail].strip():
        trail += 1
    return lead, trail


def changelog_hunk(hunk: Hunk) -> list[str]:
    _require_base_kept(hunk)
    pre_ours, ours = _blocks(hunk.ours)
    pre_theirs, theirs = _blocks(hunk.theirs)
    if not ours and not theirs:
        raise Unresolvable(f"line {hunk.start}: no slot marker in the hunk")
    core_ours, core_theirs = _strip_blank(pre_ours), _strip_blank(pre_theirs)
    if core_ours and core_theirs and core_ours != core_theirs:
        raise Unresolvable(f"line {hunk.start}: both sides changed the text before the slot markers")
    preamble = core_ours or core_theirs
    merged: dict[str, tuple[str, list[list[str]]]] = {key: (line, list(entries)) for key, line, entries in ours}
    for key, line, entries in theirs:
        if key not in merged:
            merged[key] = (line, list(entries))
            continue
        own = merged[key][1]
        # Newest first: the entries only the merged-in side has go above.
        merged[key] = (merged[key][0], [entry for entry in entries if entry not in own] + own)
    pieces = [preamble] if preamble else []
    for line, entries in merged.values():
        pieces.append([line] + [text for entry in entries for text in entry])
    lead, trail = _edge_blanks(hunk.ours if hunk.ours else hunk.theirs)
    out: list[str] = [""] * lead
    for number, piece in enumerate(pieces):
        if number:
            out.append("")
        out.extend(piece)
    return out + [""] * trail


def resolve_changelog(text: str) -> str:
    return resolve_text(text, changelog_hunk)


def marker_order(changelog_text: str) -> dict[str, int]:
    """Position of every slot marker in a (resolved) CHANGELOG.md."""
    order: dict[str, int] = {}
    for line in split_text(changelog_text)[0]:
        match = MARKER_RE.match(line)
        if match and match.group(1) not in order:
            order[match.group(1)] = len(order)
    return order


# Slot lists (SLOTS_BY_AREA and decision 0003)

PY_LINE = re.compile(r'^(?P<pre>\s*"(?P<area>[^"]+)": \[)(?P<items>[^\]]*)(?P<post>\],?\s*)$')
MD_LINE = re.compile(r"^(?P<pre>\s*- `(?P<area>[^`]+)`: )(?P<items>T\d+[a-z]?(?:, T\d+[a-z]?)*)(?P<post>\.\s*)$")


def _parse_slot_line(line: str, style: str) -> tuple[str, str, list[str], str]:
    match = (PY_LINE if style == "py" else MD_LINE).match(line)
    if not match:
        raise Unresolvable(f"not a slot list line: {line.strip()[:60]!r}")
    raw = [item.strip() for item in match.group("items").split(",") if item.strip()]
    items = [item.strip('"') for item in raw] if style == "py" else raw
    return match.group("area"), match.group("pre"), items, match.group("post")


def _render_slot_line(pre: str, items: list[str], post: str, style: str) -> str:
    body = ", ".join(f'"{item}"' for item in items) if style == "py" else ", ".join(items)
    return f"{pre}{body}{post}"


def slot_list_hunk(hunk: Hunk, order: dict[str, int], style: str) -> list[str]:
    ours = [_parse_slot_line(line, style) for line in hunk.ours if line.strip()]
    theirs = [_parse_slot_line(line, style) for line in hunk.theirs if line.strip()]
    base = {area: items for area, _, items, _ in (_parse_slot_line(line, style) for line in hunk.base or [] if line.strip())}
    if not ours and not theirs:
        raise Unresolvable(f"line {hunk.start}: empty slot list hunk")
    areas: dict[str, tuple[str, list[str], str]] = {}
    for area, pre, items, post in ours:
        areas[area] = (pre, list(items), post)
    for area, pre, items, post in theirs:
        if area not in areas:
            areas[area] = (pre, list(items), post)
        else:
            areas[area][1].extend(item for item in items if item not in areas[area][1])
    side_items = {
        "ours": {area: items for area, _, items, _ in ours},
        "theirs": {area: items for area, _, items, _ in theirs},
    }
    for area, items in base.items():
        for side in ("ours", "theirs"):
            if not set(items) <= set(side_items[side].get(area, [])):
                raise Unresolvable(f"line {hunk.start}: {side} removed a slot of {area!r}")
    out = []
    for pre, items, post in areas.values():
        known = sorted((item for item in items if item in order), key=order.__getitem__)
        out.append(_render_slot_line(pre, known + [item for item in items if item not in order], post, style))
    return out


def resolve_slot_list(text: str, order: dict[str, int], style: str) -> str:
    return resolve_text(text, lambda hunk: slot_list_hunk(hunk, order, style))


def style_of(path: str) -> str:
    return "py" if path.endswith(".py") else "md"


# Branding manifests


def validated_paths(manifests: dict[str, str]) -> set[str]:
    """Paths of the `validated` rows in a {file name: JSON text} manifest set."""
    paths: set[str] = set()
    for text in manifests.values():
        for row in json.loads(text).get("rows", []):
            if row.get("status") == "validated":
                paths.add(row["path"])
    return paths
