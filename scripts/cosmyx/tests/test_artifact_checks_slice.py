"""slice: version.inc parsing, the command line and the G-code checks."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from artifact_checks import inventory, slice as slicer  # noqa: E402

VERSION_INC = 'set(SLIC3R_APP_NAME "OrcaSlicer")\nset(SLIC3R_APP_KEY "OrcaSlicer")\nset(SoftFever_VERSION "2.6.0-dev")\n'
GOOD = ("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.6.0-dev on 2026-11-19 at 10:00:00 UTC\n"
        "; HEADER_BLOCK_END\n; CONFIG_BLOCK_START\n; layer_height = 0.2\n; CONFIG_BLOCK_END\n"
        ";TYPE:Outer wall\n" + "G1 X10 Y10 E0.5\n" * 100)


class HeaderTests(unittest.TestCase):
    def test_identity(self) -> None:
        self.assertEqual(slicer.header_identity(VERSION_INC), ("OrcaSlicer", "2.6.0-dev"))
        self.assertIsNone(slicer.header_identity('set(SLIC3R_APP_NAME "OrcaSlicer")\n'))

    def test_good_gcode(self) -> None:
        self.assertEqual(slicer.gcode_problems(GOOD, "OrcaSlicer", "2.6.0-dev", 100), [])

    def test_problems(self) -> None:
        cases = {
            "HEADER_BLOCK_START": GOOD.replace("; HEADER_BLOCK_START\n", ""),
            "generated by OrcaSlicer 2.6.0-dev": GOOD.replace("2.6.0-dev on", "2.5.0 on"),
            "CONFIG_BLOCK_START": GOOD.replace("; CONFIG_BLOCK_START", "; X"),
            ";TYPE:": GOOD.replace(";TYPE:", ";T:"),
            "99 G1 moves": GOOD.replace("G1 X10 Y10 E0.5\n", "", 1),
        }
        for expected, text in cases.items():
            with self.subTest(expected=expected):
                problems = slicer.gcode_problems(text, "OrcaSlicer", "2.6.0-dev", 100)
                self.assertEqual(len(problems), 1)
                self.assertIn(expected, problems[0])

    def test_version_with_regex_characters_is_literal(self) -> None:
        text = GOOD.replace("2.6.0-dev", "2x6x0-dev")
        self.assertTrue(slicer.gcode_problems(text, "OrcaSlicer", "2.6.0-dev", 100))


class CommandTests(unittest.TestCase):
    def test_command(self) -> None:
        args = slicer.command(Path("r/AppRun"), Path("m/cube.3mf"), Path("d"), Path("o"), [])
        self.assertEqual(args[:2], ["xvfb-run", "-a"])
        self.assertEqual(args[2:], [str(Path("r/AppRun")), "--datadir", "d", "--outputdir", "o", "--slice", "0",
                                    str(Path("m/cube.3mf"))])
        args = slicer.command(Path("AppRun"), Path("c.3mf"), Path("d"), Path("o"), ["a.json", "b.json"], xvfb=False)
        self.assertEqual(args[args.index("--load-settings") + 1], "a.json;b.json")
        self.assertEqual(args[0], "AppRun")


class RunTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.resources, self.subject, self.work = root / "res", root / "subject", root / "work"
        (self.resources / "cosmyx" / "models").mkdir(parents=True)
        (self.resources / "cosmyx" / "models" / "cosmyx_cube.3mf").write_bytes(b"3mf")
        self.subject.mkdir()
        (self.subject / "version.inc").write_text(VERSION_INC, encoding="utf-8")
        self.expectations = inventory.load_expectations()

    def runner(self, gcode: str | None, code: int = 0):
        def run(args, **kwargs):
            out = Path(args[args.index("--outputdir") + 1])
            (out / "result.json").write_text(json.dumps({"return_code": code}), encoding="utf-8")
            if gcode is not None:
                (out / "plate_1.gcode").write_text(gcode, encoding="utf-8")
            return subprocess.CompletedProcess(args, code, "", "error line")
        return run

    def slice(self, run):
        return slicer.run_slice("app", Path("AppRun"), self.resources, self.subject, self.work, self.expectations,
                                run, xvfb=False)

    def test_pass(self) -> None:
        record = self.slice(self.runner(GOOD))
        self.assertEqual(record.status, "pass")
        self.assertEqual(record.details["plates"], ["plate_1.gcode"])

    def test_return_code_and_no_plate(self) -> None:
        record = self.slice(self.runner(None, code=-5))
        self.assertEqual(record.status, "fail")
        self.assertIn("return_code -5", record.reason)
        self.assertIn("no plate_", record.reason)

    def test_timeout(self) -> None:
        def hang(args, **kwargs):
            raise subprocess.TimeoutExpired(args, kwargs["timeout"])
        self.assertEqual(self.slice(hang).status, "fail")

    def test_model_not_shipped_skips(self) -> None:
        (self.resources / "cosmyx" / "models" / "cosmyx_cube.3mf").unlink()
        record = self.slice(self.runner(GOOD))
        self.assertEqual(record.status, "skip")
        self.assertIn("T5", record.reason)


if __name__ == "__main__":
    unittest.main()
