TAG = "2.6.0-dev-8_aa9dac8"
VERSION_INC = 'set(SLIC3R_APP_NAME "OrcaSlicer")\nset(SoftFever_VERSION "2.6.0-dev")\n'
GOOD = ("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.6.0-dev on 2026-11-19 at 10:00:00 UTC\n"
        "; HEADER_BLOCK_END\n; CONFIG_BLOCK_START\n; CONFIG_BLOCK_END\n;TYPE:Outer wall\n" + "G1 X1 Y1 E1\n" * 100)
ARCHIVE = b"fake 7z"
DLLS = {"x64/opengl32.dll": b"gl", "x64/libgallium_wgl.dll": b"gallium"}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def expectations() -> dict:
    data = inventory.load_expectations()
    data["mesa_win"] = dict(data["mesa_win"], url="https://example.invalid/1/mesa3d-1-release-msvc.7z",
                            sha256=sha(ARCHIVE), files={k: sha(v) for k, v in DLLS.items()})
    return data


def make_resources(root: Path, model: bool = True) -> None:
    for name in ("i18n", "profiles"):
        (root / name).mkdir(parents=True, exist_ok=True)
    if model:
        (root / "cosmyx" / "models").mkdir(parents=True, exist_ok=True)
        (root / "cosmyx" / "models" / "cosmyx_cube.3mf").write_bytes(b"3mf")


class FakeApp:
    """Answers --help, a slice, 7-Zip and the macOS tools."""

    def __init__(self, help_code: int = 0, slice_code: int = 0, gcode: str | None = GOOD,
                 hang: str = "") -> None:
        self.help_code, self.slice_code, self.gcode, self.hang, self.calls = help_code, slice_code, gcode, hang, []

    def __call__(self, args, **kwargs):
        args = [str(a) for a in args]
        self.calls.append((args, kwargs))
        if args[0] in ("lipo", "codesign", "hdiutil"):
            return subprocess.CompletedProcess(args, 0, "arm64 x86_64\n", "Signature=adhoc\n")
        if len(args) > 1 and args[1] == "e":
            target = Path(next(a for a in args if a.startswith("-o"))[2:])
            for member in args[5:]:
                (target / member.split("/")[-1]).write_bytes(DLLS[member])
            return subprocess.CompletedProcess(args, 0, "", "")
        if "--help" in args:
            if self.hang == "help":
                raise subprocess.TimeoutExpired(args, kwargs["timeout"])
            return subprocess.CompletedProcess(args, self.help_code, "Usage: orca-slicer [ OPTIONS ]", "")
        if "--slice" in args:
            if self.hang == "slice":
                raise subprocess.TimeoutExpired(args, kwargs["timeout"])
            out = Path(args[args.index("--outputdir") + 1])
            (out / "result.json").write_text(json.dumps({"return_code": self.slice_code}), encoding="utf-8")
            if self.gcode is not None:
                (out / "plate_1.gcode").write_text(self.gcode, encoding="utf-8")
            return subprocess.CompletedProcess(args, self.slice_code, "", "")
        raise AssertionError(f"unexpected {args}")

    def app_calls(self):
        return [(a, k) for a, k in self.calls if "--help" in a or "--slice" in a]


def by_check(records):
    return {r.check: r for r in records}


class ClassifyTests(unittest.TestCase):
    def test_windows_ntstatus_crashes(self) -> None:
        for code, name in ((0xC0000005, "ACCESS_VIOLATION"), (-1073741819, "ACCESS_VIOLATION"),
                           (0xC0000409, "STACK_BUFFER_OVERRUN"), (0xC0000135, "DLL_NOT_FOUND"),
                           (0xC0001234, "NTSTATUS 0xC0001234")):
            with self.subTest(code=code):
                status, reason = smoke_native.classify("windows", code, "Usage:", False, 60)
                self.assertEqual(status, "fail")
                self.assertIn(name, reason)

    def test_windows_ordinary_exits(self) -> None:
        self.assertEqual(smoke_native.classify("windows", 0, "", False, 60)[0], "pass")
        self.assertEqual(smoke_native.classify("windows", 1, "usage: x", False, 60)[0], "pass")
        self.assertEqual(smoke_native.classify("windows", 1, "boom", False, 60)[0], "fail")

    def test_timeout(self) -> None:
        for os_name in ("windows", "macos"):
            status, reason = smoke_native.classify(os_name, None, "", True, 60)
            self.assertEqual((status, reason), ("fail", "did not exit within 60 s"))

    def test_macos_signals(self) -> None:
        status, reason = smoke_native.classify("macos", -signal.SIGSEGV, "", False, 60)
        self.assertEqual(status, "fail")
        self.assertIn("SIGSEGV", reason)
        self.assertEqual(smoke_native.classify("macos", 0, "", False, 60)[0], "pass")


class SmokeTests(unittest.TestCase):
    def test_command_timeout_and_env(self) -> None:
        app = FakeApp()
        record = smoke_native.smoke("windows", "a", Path("dir/orca-slicer.exe"), "orca-slicer.exe --help", 60, app,
                                    {"X": "1"})
        args, kwargs = app.calls[0]
        self.assertEqual(args, [str(Path("dir/orca-slicer.exe")), "--help"])
        self.assertEqual(kwargs["timeout"], 60)
        self.assertEqual(kwargs["env"], {"X": "1"})
        self.assertEqual(record.status, "pass")

    def test_hang_and_missing_exe(self) -> None:
        record = smoke_native.smoke("macos", "a", Path("x"), "x --help", 5, FakeApp(hang="help"))
        self.assertEqual(record.status, "fail")
        self.assertIn("5 s", record.reason)

        def missing(args, **_kwargs):
            raise FileNotFoundError(2, "No such file", args[0])
        record = smoke_native.smoke("macos", "a", Path("x"), "x --help", 5, missing)
        self.assertEqual(record.status, "fail")
        self.assertIn("could not start", record.reason)


class WindowsTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.portable, self.subject, self.work = root / "portable", root / "subject", root / "work"
        self.portable.mkdir()
        (self.portable / "orca-slicer.exe").write_bytes(b"MZ")
        make_resources(self.portable / "resources")
        self.subject.mkdir()
        (self.subject / "version.inc").write_text(VERSION_INC, encoding="utf-8")
        self.expectations = expectations()

    def artifact(self, arch: str = "x64") -> inventory.Artifact:
        return inventory.classify(f"OrcaSlicer_Windows_{TAG}_{arch}_portable", self.expectations)

    def records(self, app, arch="x64", exec_ok=True, seven_zip="7z.exe", payload=ARCHIVE):
        return smoke_native.windows_records(self.artifact(arch), self.portable, self.subject, self.work,
                                            self.expectations, exec_ok, {"PATH": "sysbin"}, app,
                                            lambda url, timeout=None: io.BytesIO(payload), seven_zip, pause=0)

    def test_pass_runs_from_a_copy_with_mesa(self) -> None:
        app = FakeApp()
        records = by_check(self.records(app))
        self.assertEqual(records["smoke"].status, "pass")
        self.assertEqual(records["slice"].status, "pass", records["slice"].reason)
        self.assertEqual(records["slice"].os, "windows")
        (smoke_args, smoke_kwargs), (slice_args, slice_kwargs) = app.app_calls()
        copy = self.work / self.artifact().name / "run" / "app"
        self.assertEqual(smoke_args, [str(copy / "orca-slicer.exe"), "--help"])
        self.assertEqual(slice_args[0], str(copy / "orca-slicer.exe"))
        self.assertNotIn("xvfb-run", slice_args)
        self.assertNotIn("--sw-renderer", slice_args)
        self.assertEqual(slice_args[-1], str(copy / "resources" / "cosmyx" / "models" / "cosmyx_cube.3mf"))
        self.assertEqual(slice_kwargs["timeout"], 300)
        self.assertEqual(smoke_kwargs["timeout"], 60)
        self.assertEqual(slice_kwargs["env"]["GALLIUM_DRIVER"], "llvmpipe")
        self.assertTrue(slice_kwargs["env"]["PATH"].startswith(str(copy / "mesa")))
        self.assertEqual((copy / "mesa" / "opengl32.dll").read_bytes(), b"gl")
        self.assertEqual((copy / "opengl32.dll").read_bytes(), b"gl")
        self.assertFalse((self.portable / "mesa").exists(), "the downloaded artifact is never changed")
        self.assertEqual(records["smoke"].details["mesa_files"], ["libgallium_wgl.dll", "opengl32.dll"])

    def test_slice_crash_is_named(self) -> None:
        records = by_check(self.records(FakeApp(slice_code=0xC0000005, gcode=None)))
        self.assertEqual(records["slice"].status, "fail")
        self.assertIn("STATUS_ACCESS_VIOLATION", records["slice"].reason)

    def test_slice_timeout(self) -> None:
        records = by_check(self.records(FakeApp(hang="slice")))
        self.assertEqual(records["slice"].status, "fail")
        self.assertIn("300 s", records["slice"].reason)

    def test_bad_gcode_fails(self) -> None:
        records = by_check(self.records(FakeApp(gcode=GOOD.replace("; CONFIG_BLOCK_START", ""))))
        self.assertEqual(records["slice"].status, "fail")
        self.assertIn("CONFIG_BLOCK_START", records["slice"].reason)

    def test_mesa_hash_mismatch_fails_both(self) -> None:
        app = FakeApp()
        records = by_check(self.records(app, payload=b"tampered"))
        for check in ("smoke", "slice"):
            self.assertEqual(records[check].status, "fail")
            self.assertIn("SHA-256", records[check].reason)
        self.assertEqual(app.app_calls(), [])

    def test_missing_seven_zip_skips_with_reason(self) -> None:
        records = by_check(self.records(FakeApp(), seven_zip=""))
        for check in ("smoke", "slice"):
            self.assertEqual(records[check].status, "skip")
            self.assertIn("7-Zip", records[check].reason)
            self.assertFalse(records[check].by_design, "strict mode must fail a missing tool")

    def test_fork_and_arm64_skip_by_design(self) -> None:
        app = FakeApp()
        for records in (self.records(app, exec_ok=False), self.records(app, arch="arm64")):
            self.assertEqual({r.check for r in records}, {"smoke", "slice"})
            self.assertTrue(all(r.status == "skip" and r.by_design for r in records))
        self.assertEqual(app.calls, [])

    def test_missing_exe_fails(self) -> None:
        (self.portable / "orca-slicer.exe").unlink()
        records = by_check(self.records(FakeApp()))
        self.assertEqual(records["smoke"].status, "fail")


class MacTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.mount, self.subject, self.work = root / "mnt", root / "subject", root / "work"
        contents = self.mount / "OrcaSlicer.app" / "Contents"
        (contents / "MacOS").mkdir(parents=True)
        (contents / "MacOS" / "OrcaSlicer").write_bytes(b"\xcf\xfa\xed\xfe")
        with open(contents / "Info.plist", "wb") as handle:
            plistlib.dump({"CFBundleExecutable": "OrcaSlicer"}, handle)
        make_resources(contents / "Resources")
        self.subject.mkdir()
        (self.subject / "version.inc").write_text(VERSION_INC, encoding="utf-8")
        self.expectations = inventory.load_expectations()

    def artifact(self, family: str = "universal") -> inventory.Artifact:
        return inventory.classify(f"OrcaSlicer_Mac_{family}_{TAG}", self.expectations)

    def records(self, app, family="universal", exec_ok=True, host="arm64"):
        return smoke_native.macos_records(self.artifact(family), self.mount, self.subject, self.work,
                                          self.expectations, exec_ok, app, host)

    def test_pass_runs_the_bundle_executable(self) -> None:
        app = FakeApp()
        records = by_check(self.records(app))
        self.assertEqual(records["smoke"].status, "pass")
        self.assertEqual(records["smoke"].path, "OrcaSlicer.app/Contents/MacOS/OrcaSlicer --help")
        self.assertEqual(records["slice"].status, "pass", records["slice"].reason)
        exe = str(self.mount / "OrcaSlicer.app" / "Contents" / "MacOS" / "OrcaSlicer")
        (smoke_args, _), (slice_args, slice_kwargs) = app.app_calls()
        self.assertEqual(smoke_args, [exe, "--help"])
        self.assertEqual(slice_args[0], exe)
        self.assertNotIn("env", slice_kwargs)
        self.assertEqual(slice_kwargs["timeout"], 300)

    def test_executable_name_from_info_plist(self) -> None:
        contents = self.mount / "OrcaSlicer.app" / "Contents"
        with open(contents / "Info.plist", "wb") as handle:
            plistlib.dump({"CFBundleExecutable": "Other"}, handle)
        records = by_check(self.records(FakeApp()))
        self.assertEqual(records["smoke"].status, "fail")
        self.assertIn("MacOS/Other", records["smoke"].reason)

    def test_executable_name_must_be_a_plain_file_name(self) -> None:
        contents = self.mount / "OrcaSlicer.app" / "Contents"
        for name in ("..", "a/b", "a\\b", "", "x\0y"):
            with open(contents / "Info.plist", "wb") as handle:
                # Binary format: XML plists cannot carry the NUL case.
                plistlib.dump({"CFBundleExecutable": name}, handle, fmt=plistlib.FMT_BINARY)
            self.assertEqual(smoke_native.app_executable(self.mount / "OrcaSlicer.app"),
                             contents / "MacOS" / "OrcaSlicer", repr(name))

    def test_damaged_info_plist_falls_back_to_the_bundle_name(self) -> None:
        contents = self.mount / "OrcaSlicer.app" / "Contents"
        for damaged in ("<?xml version=\"1.0\"?><plist><dict>", "<plist><date>x</date></plist>"):
            (contents / "Info.plist").write_text(damaged, encoding="utf-8")
            self.assertEqual(smoke_native.app_executable(self.mount / "OrcaSlicer.app"),
                             contents / "MacOS" / "OrcaSlicer", damaged)

    @unittest.skipIf(sys.platform == "win32", "symlinks need extra rights on Windows")
    def test_executable_symlinked_out_of_the_bundle_is_never_run(self) -> None:
        contents = self.mount / "OrcaSlicer.app" / "Contents"
        outside = Path(self.tmp.name) / "outside"
        outside.write_bytes(b"\xcf\xfa\xed\xfe")
        (contents / "MacOS" / "OrcaSlicer").unlink()
        (contents / "MacOS" / "OrcaSlicer").symlink_to(outside)
        app = FakeApp()
        records = by_check(self.records(app))
        self.assertEqual(records["smoke"].status, "fail")
        self.assertIn("outside Contents/MacOS", records["smoke"].reason)
        self.assertEqual(app.app_calls(), [])

    def test_crash_signal_on_slice(self) -> None:
        records = by_check(self.records(FakeApp(slice_code=-signal.SIGABRT, gcode=None)))
        self.assertEqual(records["slice"].status, "fail")
        self.assertIn("SIGABRT", records["slice"].reason)

    def test_skips_by_design(self) -> None:
        app = FakeApp()
        for records in (self.records(app, exec_ok=False), self.records(app, family="x86_64", host="arm64")):
            self.assertTrue(all(r.status == "skip" and r.by_design for r in records))
        self.assertEqual(app.calls, [])
        self.assertEqual(by_check(self.records(app, family="arm64"))["smoke"].status, "pass")

    def test_macos_check_runs_it_while_mounted(self) -> None:
        artifacts = Path(self.tmp.name) / "artifacts"
        folder = artifacts / self.artifact().name
        folder.mkdir(parents=True)
        (folder / "OrcaSlicer.dmg").write_bytes(b"dmg")
        app = FakeApp()
        records = macos.check(artifacts, [self.artifact()], self.work, allowlist.Allowlist(), app, None, None,
                              exec_ok=True, subject=self.subject, expectations=self.expectations, host_arch="arm64")
        # The fake hdiutil mounts nothing: the empty mount has no .app.
        self.assertEqual(by_check(records)["smoke"].status, "fail")
        commands = [a[:2] for a, _ in app.calls]
        self.assertLess(commands.index(["hdiutil", "attach"]), commands.index(["hdiutil", "detach"]))


